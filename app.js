// Data Repository Manager
class NewsRepository {
    constructor() {
        // Overwrite or populate news storage so user sees the 90+ rich demo articles
        localStorage.setItem('ourtimes_news', JSON.stringify(RAW_NEWS_DATA));
        if (!localStorage.getItem('ourtimes_ads_config')) {
            localStorage.setItem('ourtimes_ads_config', JSON.stringify({
                headerLeaderboard: false,
                sidebarRectangle: false,
                inArticleBanner: false
            }));
        }
    }

    getAllNews() {
        return JSON.parse(localStorage.getItem('ourtimes_news')) || RAW_NEWS_DATA;
    }

    getNewsById(id) {
        return this.getAllNews().find(n => n.id === id);
    }

    saveNews(newsItem) {
        const all = this.getAllNews();
        const index = all.findIndex(n => n.id === newsItem.id);
        if (index >= 0) {
            all[index] = newsItem;
        } else {
            all.unshift(newsItem);
        }
        localStorage.setItem('ourtimes_news', JSON.stringify(all));
    }

    deleteNews(id) {
        const filtered = this.getAllNews().filter(n => n.id !== id);
        localStorage.setItem('ourtimes_news', JSON.stringify(filtered));
    }

    getAdConfig() {
        return JSON.parse(localStorage.getItem('ourtimes_ads_config')) || {};
    }

    setAdConfig(config) {
        localStorage.setItem('ourtimes_ads_config', JSON.stringify(config));
    }
}

